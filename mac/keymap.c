int tfx_mac_scan(uint16_t keycode, int down, uint8_t out[2]) {
    uint16_t s = keycode < 128 ? scan[keycode] : 0;
    if (!s)
        return 0;
    int n = 0;
    if (s & E)
        out[n++] = 0xe0;
    out[n++] = (uint8_t)((s & 0x7f) | (down ? 0 : 0x80));
    return n;
}

int tfx_mac_modifier(uint16_t keycode) {
    return keycode == 0x38 || keycode == 0x39 || keycode == 0x3a || keycode == 0x3b || keycode == 0x3c ||
           keycode == 0x3d || keycode == 0x3e;
}
